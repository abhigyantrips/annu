export const countryName = (code: string) => {
  try {
    return new Intl.DisplayNames(["en"], { type: "region" }).of(code) || code;
  } catch {
    return code;
  }
};
export const siteName = (url: string) => {
  try {
    return new URL(url).host;
  } catch {
    return url;
  }
};
